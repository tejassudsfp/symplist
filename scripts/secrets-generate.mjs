// Prints fresh values for every generated secret family (architecture §4.5, §16.3) in .env format:
// `<NAME>_1=<32 random bytes, base64url>` and `<NAME>_CURRENT=1`. It only writes to stdout and
// never creates or changes files; copy the values into apps/api/.env and apps/worker/.env yourself.
//
// Usage: pnpm secrets:generate
import { randomBytes } from "node:crypto";
import {
  generatedSecretBytes,
  generatedSecretFamilies,
  secretFamilyInventory,
} from "../packages/config/src/secrets.ts";

/** `<NAME>_1` with a fresh value and `<NAME>_CURRENT=1` for each family. */
function familyLines(families) {
  return families.flatMap((family) => [
    `${family}_1=${randomBytes(generatedSecretBytes).toString("base64url")}`,
    `${family}_CURRENT=1`,
  ]);
}

/** The .env text with fresh values for every generated family, shared families first. */
function generate() {
  const shared = generatedSecretFamilies.filter(
    (family) => secretFamilyInventory[family].worker === "yes",
  );
  const apiOnly = generatedSecretFamilies.filter(
    (family) => secretFamilyInventory[family].worker !== "yes",
  );
  return [
    "# Generated by pnpm secrets:generate. These are secrets: never commit, log or share them.",
    "# Each family is <NAME>_<n> (32 random bytes, base64url) plus <NAME>_CURRENT=<n>.",
    "",
    "# Shared by the api and the worker: use the same values in apps/api/.env and apps/worker/.env.",
    ...familyLines(shared),
    "",
    "# api only: the worker refuses to start when any of these is set.",
    ...familyLines(apiOnly),
  ].join("\n");
}

// Exit codes go through process.exitCode rather than process.exit(), so output written to a pipe is
// flushed before the process ends (pipe writes are asynchronous on macOS).
const args = process.argv.slice(2);
if (args.length === 1 && (args[0] === "--help" || args[0] === "-h")) {
  process.stdout.write(
    "Usage: pnpm secrets:generate\nPrints fresh _1 values and _CURRENT=1 for every generated secret family.\n",
  );
} else if (args.length > 0) {
  process.stderr.write("secrets:generate takes no arguments; it only prints to stdout.\n");
  process.exitCode = 2;
} else {
  process.stdout.write(`${generate()}\n`);
}
